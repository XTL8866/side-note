const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('native', {
  isApp: true,
  setState: (s) => ipcRenderer.send('win:state', s),
  setPrefs: (p) => ipcRenderer.send('app:prefs', p),
  requestOpen: () => ipcRenderer.send('dock:want-open'),
  requestClose: (force) => ipcRenderer.send('dock:want-close', !!force),
  dragStart: () => ipcRenderer.send('drag:start'),
  dragEnd: () => ipcRenderer.send('drag:end'),
  setTop: (v) => ipcRenderer.send('win:top', v),
  setAutoStart: (v) => ipcRenderer.send('app:autostart', v),
  quit: () => ipcRenderer.send('app:quit'),
  hide: () => ipcRenderer.send('win:hide'),
  getBounds: () => ipcRenderer.invoke('win:bounds'),
  isVisible: () => ipcRenderer.invoke('test:visible'),
  fsState: () => ipcRenderer.invoke('test:fs'),
  testFullscreen: (v) => ipcRenderer.send('test:fullscreen', !!v),
  testOccluded: (v) => ipcRenderer.send('test:occluded', !!v),
  testOccRect: (r) => ipcRenderer.send('test:occRect', r),
  testShow: () => ipcRenderer.send('test:show'),
  testCursor: (x, y) => ipcRenderer.send('test:cursor', { x, y }),
  remind: (t) => ipcRenderer.send('app:remind', t),
  releaseHold: () => ipcRenderer.send('hold:release'),
  remindLog: () => ipcRenderer.invoke('test:remind-log'),
  isTop: () => ipcRenderer.invoke('test:top'),
  testFocus: (d) => ipcRenderer.send('test:focus', d),
  isTest: process.env.SIDENOTE_TEST === '1',
  onVisual: (cb) => ipcRenderer.on('dock:visual', (_e, d) => cb(d)),
  onMoved: (cb) => ipcRenderer.on('win:moved', (_e, d) => cb(d)),
  onAction: (cb) => ipcRenderer.on('tray:action', (_e, d) => cb(d)),
  onQuickAdd: (cb) => ipcRenderer.on('app:quickadd', () => cb()),
  onFocusTask: (cb) => ipcRenderer.on('app:focus-task', (_e, d) => cb(d)),
  onRemindDisplay: (cb) => ipcRenderer.on('app:remind-display', (_e, d) => cb(d)),
  onBlur: (cb) => ipcRenderer.on('win:blur', () => cb())
});
